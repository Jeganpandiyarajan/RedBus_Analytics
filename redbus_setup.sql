CREATE OR REPLACE TABLE REDBUS_ANALYTICS.DW.FACT_BOOKING (
    -- Surrogate Key
    BOOKING_SK NUMBER(10) IDENTITY(1,1) PRIMARY KEY,
    
    -- Business Keys (for traceability)
    BOOKING_ID VARCHAR(50),
    BOOKING_LINE_ID VARCHAR(50),
    
    -- Foreign Keys to Dimensions
    BOOKING_DATE_KEY NUMBER(8) REFERENCES REDBUS_ANALYTICS.DW.DIM_DATE(DATE_KEY),
    JOURNEY_DATE_KEY NUMBER(8) REFERENCES REDBUS_ANALYTICS.DW.DIM_DATE(DATE_KEY),
    CUSTOMER_SK NUMBER(10) REFERENCES REDBUS_ANALYTICS.DW.DIM_CUSTOMER(CUSTOMER_SK),
    ROUTE_SK NUMBER(10) REFERENCES REDBUS_ANALYTICS.DW.DIM_ROUTE(ROUTE_SK),
    BUS_SK NUMBER(10) REFERENCES REDBUS_ANALYTICS.DW.DIM_BUS(BUS_SK),
    
    -- Facts (Measurements)
    PASSENGER_COUNT NUMBER(5),
    FARE_AMOUNT NUMBER(10,2),
    DISCOUNT_PCT NUMBER(5,2),
    NET_AMOUNT NUMBER(10,2),  -- Calculated: FARE_AMOUNT * (1 - DISCOUNT_PCT/100)
    
    -- Attributes
    SEAT_TYPE VARCHAR(50),
    SEAT_NO VARCHAR(10),
    PAYMENT_MODE VARCHAR(50),
    BOOKING_STATUS VARCHAR(20),
    
    -- Audit Columns
    LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

INSERT INTO REDBUS_ANALYTICS.DW.FACT_BOOKING (
    BOOKING_ID,
    BOOKING_LINE_ID,
    BOOKING_DATE_KEY,
    JOURNEY_DATE_KEY,
    CUSTOMER_SK,
    ROUTE_SK,
    BUS_SK,
    PASSENGER_COUNT,
    FARE_AMOUNT,
    DISCOUNT_PCT,
    NET_AMOUNT,
    SEAT_TYPE,
    SEAT_NO,
    PAYMENT_MODE,
    BOOKING_STATUS,
    LOAD_TS
)
SELECT 
    b.BOOKING_ID,
    b.BOOKING_LINE_ID,
    d1.DATE_KEY AS BOOKING_DATE_KEY,
    d2.DATE_KEY AS JOURNEY_DATE_KEY,
    c.CUSTOMER_SK,
    r.ROUTE_SK,
    bu.BUS_SK,
    b.PASSENGER_COUNT,
    b.FARE_AMOUNT,
    b.DISCOUNT_PCT,
    b.FARE_AMOUNT * (1 - b.DISCOUNT_PCT / 100) AS NET_AMOUNT,
    b.SEAT_TYPE,
    b.SEAT_NO,
    b.PAYMENT_MODE,
    b.BOOKING_STATUS,
    CURRENT_TIMESTAMP() AS LOAD_TS
FROM REDBUS_ANALYTICS.RAW.RAW_BOOKINGS b
LEFT JOIN REDBUS_ANALYTICS.DW.DIM_DATE d1 
    ON b.BOOKING_DATE = d1.FULL_DATE
LEFT JOIN REDBUS_ANALYTICS.DW.DIM_DATE d2 
    ON b.JOURNEY_DATE = d2.FULL_DATE
LEFT JOIN REDBUS_ANALYTICS.DW.DIM_CUSTOMER c 
    ON b.CUSTOMER_ID = c.CUSTOMER_ID AND c.IS_CURRENT = TRUE
LEFT JOIN REDBUS_ANALYTICS.DW.DIM_ROUTE r 
    ON b.ROUTE_ID = r.ROUTE_ID
LEFT JOIN REDBUS_ANALYTICS.DW.DIM_BUS bu 
    ON b.BUS_ID = bu.BUS_ID AND bu.IS_CURRENT = TRUE;

