-- Run Some Business Queries!

-- 1 , total revenue by month
SELECT 
    JOURNEY_YEAR,
    JOURNEY_MONTH,
    SUM(NET_AMOUNT) AS TOTAL_REVENUE
FROM REDBUS_ANALYTICS.SEMANTIC.VW_BOOKINGS
GROUP BY JOURNEY_YEAR, JOURNEY_MONTH
ORDER BY JOURNEY_YEAR, JOURNEY_MONTH;

--2,  Top 5 Routes by Revenue:
SELECT 
    ROUTE_DESCRIPTION,
    COUNT(*) AS NUMBER_OF_BOOKINGS,
    SUM(NET_AMOUNT) AS TOTAL_REVENUE
FROM REDBUS_ANALYTICS.SEMANTIC.VW_BOOKINGS
WHERE BOOKING_STATUS != 'CANCELLED'
GROUP BY ROUTE_DESCRIPTION
ORDER BY TOTAL_REVENUE DESC
LIMIT 5;

-- 3 , Cancellation Rate:
SELECT 
    JOURNEY_MONTH,
    COUNT(*) AS TOTAL_BOOKINGS,
    SUM(CASE WHEN IS_CANCELLED = TRUE THEN 1 ELSE 0 END) AS CANCELLED_BOOKINGS,
    (SUM(CASE WHEN IS_CANCELLED = TRUE THEN 1 ELSE 0 END) * 100.0 / COUNT(*)) AS CANCELLATION_RATE
FROM REDBUS_ANALYTICS.SEMANTIC.VW_BOOKINGS
GROUP BY JOURNEY_MONTH
ORDER BY JOURNEY_MONTH;

-- 4, Top Operators by Revenue:
SELECT 
    OPERATOR_NAME,
    COUNT(*) AS TRIPS,
    SUM(NET_AMOUNT) AS TOTAL_REVENUE
FROM REDBUS_ANALYTICS.SEMANTIC.VW_BOOKINGS
WHERE BOOKING_STATUS != 'CANCELLED'
GROUP BY OPERATOR_NAME
ORDER BY TOTAL_REVENUE DESC;


-- 5, Executive Dashboard - Daily Summary
SELECT 
    JOURNEY_DATE,
    COUNT(DISTINCT BOOKING_ID) AS TOTAL_BOOKINGS,
    SUM(PASSENGER_COUNT) AS TOTAL_PASSENGERS,
    SUM(NET_AMOUNT) AS TOTAL_REVENUE,
    AVG(NET_AMOUNT) AS AVG_TICKET_VALUE,
    SUM(CASE WHEN IS_CANCELLED = TRUE THEN 1 ELSE 0 END) AS CANCELLED_BOOKINGS,
    ROUND(SUM(CASE WHEN IS_CANCELLED = TRUE THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS CANCELLATION_RATE
FROM REDBUS_ANALYTICS.SEMANTIC.VW_BOOKINGS
GROUP BY JOURNEY_DATE
ORDER BY JOURNEY_DATE DESC;

-- 6 ,Monthly Revenue Trend
SELECT 
    JOURNEY_YEAR,
    JOURNEY_MONTH,
    COUNT(DISTINCT BOOKING_ID) AS BOOKINGS,
    SUM(PASSENGER_COUNT) AS PASSENGERS,
    SUM(NET_AMOUNT) AS REVENUE,
    AVG(NET_AMOUNT) AS AVG_REVENUE_PER_BOOKING,
    SUM(CASE WHEN IS_CANCELLED = TRUE THEN 1 ELSE 0 END) AS CANCELLATIONS,
    ROUND(SUM(CASE WHEN IS_CANCELLED = TRUE THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS CANCEL_RATE
FROM REDBUS_ANALYTICS.SEMANTIC.VW_BOOKINGS
GROUP BY JOURNEY_YEAR, JOURNEY_MONTH
ORDER BY JOURNEY_YEAR, JOURNEY_MONTH;

-- 7, Operator Performance Analysis

SELECT 
    OPERATOR_NAME,
    COUNT(DISTINCT BOOKING_ID) AS BOOKINGS,
    SUM(PASSENGER_COUNT) AS PASSENGERS,
    SUM(NET_AMOUNT) AS REVENUE,
    AVG(NET_AMOUNT / PASSENGER_COUNT) AS AVG_FARE_PER_PASSENGER,
    ROUND(SUM(CASE WHEN IS_CANCELLED = TRUE THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS CANCEL_RATE
FROM REDBUS_ANALYTICS.SEMANTIC.VW_BOOKINGS
GROUP BY OPERATOR_NAME
ORDER BY REVENUE DESC;

-- 8,  Bus Type Performance
SELECT 
    BUS_TYPE,
    COUNT(DISTINCT BOOKING_ID) AS BOOKINGS,
    SUM(PASSENGER_COUNT) AS PASSENGERS,
    SUM(NET_AMOUNT) AS REVENUE,
    AVG(SEAT_CAPACITY) AS AVG_CAPACITY,
    ROUND(SUM(PASSENGER_COUNT) * 100.0 / SUM(SEAT_CAPACITY), 2) AS OCCUPANCY_RATE
FROM REDBUS_ANALYTICS.SEMANTIC.VW_BOOKINGS
WHERE BOOKING_STATUS != 'CANCELLED'
GROUP BY BUS_TYPE
ORDER BY REVENUE DESC;

-- 9 , Customer Segmentation Analysis
SELECT 
    CUSTOMER_SEGMENT,
    SEGMENT_DESCRIPTION,
    COUNT(DISTINCT CUSTOMER_ID) AS CUSTOMER_COUNT,
    COUNT(DISTINCT BOOKING_ID) AS BOOKINGS,
    SUM(NET_AMOUNT) AS REVENUE,
    AVG(NET_AMOUNT) AS AVG_SPEND_PER_BOOKING
FROM REDBUS_ANALYTICS.SEMANTIC.VW_BOOKINGS
WHERE BOOKING_STATUS != 'CANCELLED'
GROUP BY CUSTOMER_SEGMENT, SEGMENT_DESCRIPTION
ORDER BY REVENUE DESC;

-- 10 ,  Weekend vs Weekday Analysis
SELECT 
    JOURNEY_IS_WEEKEND,
    CASE WHEN JOURNEY_IS_WEEKEND = TRUE THEN 'Weekend' ELSE 'Weekday' END AS DAY_TYPE,
    COUNT(DISTINCT BOOKING_ID) AS BOOKINGS,
    SUM(PASSENGER_COUNT) AS PASSENGERS,
    SUM(NET_AMOUNT) AS REVENUE,
    AVG(NET_AMOUNT) AS AVG_FARE
FROM REDBUS_ANALYTICS.SEMANTIC.VW_BOOKINGS
WHERE BOOKING_STATUS != 'CANCELLED'
GROUP BY JOURNEY_IS_WEEKEND
ORDER BY JOURNEY_IS_WEEKEND;

