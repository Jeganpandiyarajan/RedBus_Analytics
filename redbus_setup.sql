-- Create Semantic Views

CREATE OR REPLACE VIEW REDBUS_ANALYTICS.SEMANTIC.VW_CUSTOMER AS
SELECT 
    CUSTOMER_SK,
    CUSTOMER_ID,
    FIRST_NAME,
    LAST_NAME,
    CONCAT(FIRST_NAME, ' ', LAST_NAME) AS FULL_NAME,
    EMAIL,
    PHONE,
    SEGMENT,
    CITY,
    STATE,
    COUNTRY,
    CASE 
        WHEN SEGMENT = 'PREMIUM' THEN 'High Value'
        WHEN SEGMENT = 'VIP' THEN 'Frequent Traveler'
        WHEN SEGMENT = 'REGULAR' THEN 'Standard'
        ELSE 'Unknown'
    END AS SEGMENT_DESCRIPTION,
    IS_CURRENT
FROM REDBUS_ANALYTICS.DW.DIM_CUSTOMER
WHERE IS_CURRENT = TRUE;

CREATE OR REPLACE VIEW REDBUS_ANALYTICS.SEMANTIC.VW_BUS AS
SELECT 
    BUS_SK,
    BUS_ID,
    OPERATOR_NAME,
    BUS_TYPE,
    SEAT_CAPACITY,
    BUS_MODEL,
    REGISTRATION_NO,
    IN_SERVICE_DATE,
    STATUS,
    CASE 
        WHEN SEAT_CAPACITY > 40 THEN 'Large Bus'
        WHEN SEAT_CAPACITY > 30 THEN 'Medium Bus'
        WHEN SEAT_CAPACITY > 20 THEN 'Small Bus'
        ELSE 'Mini Bus'
    END AS BUS_SIZE_CATEGORY,
    IS_CURRENT
FROM REDBUS_ANALYTICS.DW.DIM_BUS
WHERE IS_CURRENT = TRUE;

CREATE OR REPLACE VIEW REDBUS_ANALYTICS.SEMANTIC.VW_ROUTE AS
SELECT 
    ROUTE_SK,
    ROUTE_ID,
    SOURCE_CITY,
    DEST_CITY,
    CONCAT(SOURCE_CITY, ' → ', DEST_CITY) AS ROUTE_DESCRIPTION,
    DISTANCE_KM,
    SOURCE_STATE,
    DEST_STATE,
    REGION,
    CASE 
        WHEN DISTANCE_KM > 800 THEN 'Long Distance'
        WHEN DISTANCE_KM > 400 THEN 'Medium Distance'
        ELSE 'Short Distance'
    END AS DISTANCE_CATEGORY
FROM REDBUS_ANALYTICS.DW.DIM_ROUTE;

CREATE OR REPLACE VIEW REDBUS_ANALYTICS.SEMANTIC.VW_DATE AS
SELECT 
    DATE_KEY,
    FULL_DATE,
    YEAR,
    QUARTER,
    MONTH,
    MONTH_NAME,
    DAY,
    DAY_NAME,
    DAY_OF_WEEK,
    WEEK_OF_YEAR,
    IS_WEEKEND,
    CASE 
        WHEN IS_WEEKEND = TRUE THEN 'Weekend'
        ELSE 'Weekday'
    END AS DAY_TYPE,
    CASE 
        WHEN MONTH >= 4 THEN YEAR
        ELSE YEAR - 1
    END AS FISCAL_YEAR,
    CASE 
        WHEN MONTH BETWEEN 4 AND 6 THEN 'Q1'
        WHEN MONTH BETWEEN 7 AND 9 THEN 'Q2'
        WHEN MONTH BETWEEN 10 AND 12 THEN 'Q3'
        ELSE 'Q4'
    END AS FISCAL_QUARTER
FROM REDBUS_ANALYTICS.DW.DIM_DATE;

CREATE OR REPLACE VIEW REDBUS_ANALYTICS.SEMANTIC.VW_BOOKINGS AS
SELECT 
    -- Booking Details
    b.BOOKING_ID,
    b.BOOKING_LINE_ID,
    b.SEAT_TYPE,
    b.SEAT_NO,
    b.PAYMENT_MODE,
    b.BOOKING_STATUS,
    b.PASSENGER_COUNT,
    b.FARE_AMOUNT,
    b.DISCOUNT_PCT,
    b.NET_AMOUNT,
    
    -- Booking Date
    b.BOOKING_DATE_KEY,
    bd.FULL_DATE AS BOOKING_DATE,
    bd.YEAR AS BOOKING_YEAR,
    bd.MONTH_NAME AS BOOKING_MONTH,
    bd.QUARTER AS BOOKING_QUARTER,
    bd.DAY_NAME AS BOOKING_DAY,
    bd.IS_WEEKEND AS BOOKING_IS_WEEKEND,
    
    -- Journey Date
    b.JOURNEY_DATE_KEY,
    jd.FULL_DATE AS JOURNEY_DATE,
    jd.YEAR AS JOURNEY_YEAR,
    jd.MONTH_NAME AS JOURNEY_MONTH,
    jd.QUARTER AS JOURNEY_QUARTER,
    jd.DAY_NAME AS JOURNEY_DAY,
    jd.IS_WEEKEND AS JOURNEY_IS_WEEKEND,
    
    -- Customer Details
    b.CUSTOMER_SK,
    c.CUSTOMER_ID,
    c.FULL_NAME AS CUSTOMER_NAME,
    c.SEGMENT AS CUSTOMER_SEGMENT,
    c.CITY AS CUSTOMER_CITY,
    c.STATE AS CUSTOMER_STATE,
    c.COUNTRY AS CUSTOMER_COUNTRY,
    c.SEGMENT_DESCRIPTION,
    
    -- Route Details
    b.ROUTE_SK,
    r.ROUTE_ID,
    r.SOURCE_CITY,
    r.DEST_CITY,
    r.ROUTE_DESCRIPTION,
    r.DISTANCE_KM,
    r.REGION,
    r.DISTANCE_CATEGORY,
    
    -- Bus Details
    b.BUS_SK,
    bu.BUS_ID,
    bu.OPERATOR_NAME,
    bu.BUS_TYPE,
    bu.SEAT_CAPACITY,
    bu.BUS_SIZE_CATEGORY,
    bu.BUS_MODEL,
    bu.STATUS AS BUS_STATUS,
    
    -- Calculated Metrics
    b.FARE_AMOUNT / NULLIF(b.PASSENGER_COUNT, 0) AS FARE_PER_PASSENGER,
    b.NET_AMOUNT / NULLIF(b.PASSENGER_COUNT, 0) AS NET_PER_PASSENGER,
    CASE 
        WHEN b.BOOKING_STATUS = 'CANCELLED' THEN TRUE 
        ELSE FALSE 
    END AS IS_CANCELLED,
    CASE 
        WHEN b.BOOKING_STATUS = 'CANCELLED' THEN b.NET_AMOUNT 
        ELSE 0 
    END AS CANCELLED_REVENUE,
    CASE 
        WHEN b.BOOKING_STATUS != 'CANCELLED' THEN b.NET_AMOUNT 
        ELSE 0 
    END AS CONFIRMED_REVENUE
    
FROM REDBUS_ANALYTICS.DW.FACT_BOOKING b
